import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from PIL import Image # For image manipulation

# Libraries for image augmentation/enhancement
import cv2 # OpenCV for image processing
from skimage import io, transform # scikit-image for image I/O and transformations
from tensorflow.keras.preprocessing.image import ImageDataGenerator # Keras for augmentation
import albumentations as A # A popular library for image augmentation

import os
save_folder = r"D:\Deep Learning Course\Codes\Augmented Images"
os.makedirs(save_folder, exist_ok=True)

from tensorflow.keras.preprocessing.image import ImageDataGenerator

datagen = ImageDataGenerator(
    rotation_range=40,
    width_shift_range=0.2,
    height_shift_range=0.2,
    shear_range=0.2,
    zoom_range=0.2,
    horizontal_flip=True,
    brightness_range=(0.5, 1.5)
)

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Input, Flatten, Dense

model = Sequential([
    Input(shape=(28, 28)),
    Flatten(),
    Dense(128, activation='relu'),
    Dense(64, activation='relu'),
    Dense(10, activation='softmax')
])

model.summary()

from tensorflow.keras.utils import load_img, img_to_array

img = load_img("images.jpeg")

x = img_to_array(img)

x = x.reshape((1,) + x.shape)

import os
import matplotlib.pyplot as plt

# Ensure a valid local path in Google Colab
if 'save_folder' not in globals():
    save_folder = '/content/augmented_images'
os.makedirs(save_folder, exist_ok=True)

i = 0
for batch in datagen.flow(x, batch_size=1,
                          save_to_dir=save_folder,
                          save_prefix='image',
                          save_format='jpeg'):
  # Fixed typo: 'unit8' -> 'uint8'
  augmented_image = batch[0].astype('uint8')

  plt.figure()
  plt.imshow(augmented_image)
  plt.axis('off')
  plt.show()

  i += 1
  if i > 20:
    break

print(f"Augmented images are saved in folder: {os.path.abspath(save_folder)}")

