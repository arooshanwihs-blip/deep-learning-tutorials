"""## 5. Function for object detection"""

@torch.inference_mode()
def detect(model, image, score_threshold=0.50):
    # image: PIL RGB image
    tensor = to_tensor(image).to(DEVICE)
    output = model([tensor])[0]
    boxes = output["boxes"].detach().cpu().numpy()
    labels = output["labels"].detach().cpu().numpy()
    scores = output["scores"].detach().cpu().numpy()
    keep = np.isin(labels, [COCO_CAT_ID, COCO_DOG_ID]) & (scores >= score_threshold)
    return {
        "boxes": boxes[keep],
        "labels": labels[keep],
        "scores": scores[keep]
    }

def display_detections(image, prediction, title="", score_threshold=0.0):
    shown = image.copy()
    draw = ImageDraw.Draw(shown)
    for box, label_id, score in zip(prediction["boxes"], prediction["labels"], prediction["scores"]):
        if score < score_threshold:
            continue
        x1, y1, x2, y2 = map(float, box)
        name = COCO_NAMES.get(int(label_id), str(label_id))
        draw.rectangle([x1, y1, x2, y2], outline="red", width=3)
        draw.text((x1, max(0, y1-18)), f"{name}: {score:.2f}", fill="red")
    plt.figure(figsize=(10, 7))
    plt.imshow(shown); plt.title(title); plt.axis("off"); plt.show()

