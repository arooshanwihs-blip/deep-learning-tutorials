def predict_image(model, image_tensor, threshold=0.5):
    model.eval()
    with torch.no_grad():
        out = model([image_tensor.to(device)])[0]
    keep = out["scores"].cpu() >= threshold
    return {
        "boxes": out["boxes"].cpu()[keep],
        "labels": out["labels"].cpu()[keep],
        "scores": out["scores"].cpu()[keep],
    }

def display_predictions(image_tensor, pred):
    img = TF.to_pil_image(image_tensor.cpu())
    draw = ImageDraw.Draw(img)
    for box, label, score in zip(pred["boxes"], pred["labels"], pred["scores"]):
        x1, y1, x2, y2 = box.tolist()
        name = CLASSES[int(label)-1]
        draw.rectangle([x1, y1, x2, y2], outline="red", width=3)
        draw.text((x1, max(0, y1-15)), f"{name}: {float(score):.2f}", fill="red")
    plt.figure(figsize=(10, 7))
    plt.imshow(img)
    plt.axis("off")
    plt.show()

