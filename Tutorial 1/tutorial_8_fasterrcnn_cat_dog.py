"""## 7. Build Faster R-CNN and inspect the architecture"""

NUM_CLASSES = len(CLASSES) + 1  # background + cat + dog

def build_model(num_classes, min_size=480, max_size=800):
    # COCO-pretrained detector; replace final predictor for cat/dog/background.
    model = fasterrcnn_resnet50_fpn(weights="DEFAULT")
    in_features = model.roi_heads.box_predictor.cls_score.in_features
    model.roi_heads.box_predictor = FastRCNNPredictor(in_features, num_classes)
    model.transform.min_size = (min_size,)
    model.transform.max_size = max_size
    return model

