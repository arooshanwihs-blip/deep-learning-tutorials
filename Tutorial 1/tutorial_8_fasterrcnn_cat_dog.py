"""## 12. IoU, precision and recall"""

def calculate_iou(box1, box2):
    x1, y1 = max(box1[0], box2[0]), max(box1[1], box2[1])
    x2, y2 = min(box1[2], box2[2]), min(box1[3], box2[3])
    inter = max(0, x2-x1) * max(0, y2-y1)
    a1 = max(0, box1[2]-box1[0]) * max(0, box1[3]-box1[1])
    a2 = max(0, box2[2]-box2[0]) * max(0, box2[3]-box2[1])
    union = a1 + a2 - inter
    return inter / union if union > 0 else 0.0

def precision_recall_one_image(pred, target, iou_threshold=0.5):
    pboxes = pred["boxes"].numpy()
    plabels = pred["labels"].numpy()
    pscores = pred["scores"].numpy()
    gtboxes = target["boxes"].numpy()
    gtlabels = target["labels"].numpy()

    matched = set()
    tp = fp = 0
    for i in np.argsort(-pscores):
        best_iou, best_j = 0.0, None
        for j, gt in enumerate(gtboxes):
            if j in matched or plabels[i] != gtlabels[j]:
                continue
            iou = calculate_iou(pboxes[i], gt)
            if iou > best_iou:
                best_iou, best_j = iou, j
        if best_j is not None and best_iou >= iou_threshold:
            tp += 1
            matched.add(best_j)
        else:
            fp += 1
    fn = len(gtboxes) - len(matched)
    precision = tp/(tp+fp) if tp+fp else 0.0
    recall = tp/(tp+fn) if tp+fn else 0.0
    return {"TP": tp, "FP": fp, "FN": fn,
            "Precision": precision, "Recall": recall}

