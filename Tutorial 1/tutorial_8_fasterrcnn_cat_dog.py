"""## 4. Dataset class for Pascal VOC XML annotations"""

class CatDogDetectionDataset(Dataset):
    def __init__(self, paths, classes, augment=False):
        self.images = list(paths)
        self.classes = classes
        self.class_to_id = {name: i + 1 for i, name in enumerate(classes)}
        self.augment = augment

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        image_path = self.images[idx]
        image = Image.open(image_path).convert("RGB")
        root = ET.parse(image_path.with_suffix(".xml")).getroot()

        boxes, labels, areas, difficult = [], [], [], []
        for obj in root.findall("object"):
            name = obj.findtext("name", default="").strip().lower()
            if name not in self.class_to_id:
                continue
            box_node = obj.find("bndbox")
            if box_node is None:
                continue

            # Pascal VOC coordinates are conventionally 1-based.
            xmin = float(box_node.findtext("xmin", "0")) - 1
            ymin = float(box_node.findtext("ymin", "0")) - 1
            xmax = float(box_node.findtext("xmax", "0"))
            ymax = float(box_node.findtext("ymax", "0"))

            xmin = max(0, min(xmin, image.width - 1))
            ymin = max(0, min(ymin, image.height - 1))
            xmax = max(0, min(xmax, image.width))
            ymax = max(0, min(ymax, image.height))

            if xmax > xmin and ymax > ymin:
                boxes.append([xmin, ymin, xmax, ymax])
                labels.append(self.class_to_id[name])
                areas.append((xmax - xmin) * (ymax - ymin))
                difficult.append(int(obj.findtext("difficult", "0")))

        image = TF.to_tensor(image)
        boxes = torch.tensor(boxes, dtype=torch.float32).reshape(-1, 4)
        labels = torch.tensor(labels, dtype=torch.int64)

        if self.augment and random.random() < 0.5:
            image = TF.hflip(image)
            width = image.shape[-1]
            if len(boxes):
                old = boxes.clone()
                boxes[:, 0] = width - old[:, 2]
                boxes[:, 2] = width - old[:, 0]

        target = {
            "boxes": boxes,
            "labels": labels,
            "image_id": torch.tensor([idx]),
            "area": torch.tensor(areas, dtype=torch.float32),
            "iscrowd": torch.zeros((len(labels),), dtype=torch.int64),
        }
        return image, target

def collate_fn(batch):
    return tuple(zip(*batch))

