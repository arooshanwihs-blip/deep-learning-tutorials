# Load pretrained MobileNet V2
transfer_weights = models.MobileNet_V2_Weights.DEFAULT

transfer_model = models.mobilenet_v2(
    weights=transfer_weights
)

# Freeze pretrained feature-extraction layers
for parameter in transfer_model.features.parameters():
    parameter.requires_grad = False

# Replace the final classification layer
input_features = transfer_model.classifier[1].in_features

transfer_model.classifier[1] = nn.Linear(
    input_features,
    len(class_names)
)

transfer_model = transfer_model.to(device)

# Only train the new classifier
criterion = nn.CrossEntropyLoss()

optimizer = torch.optim.Adam(
    transfer_model.classifier.parameters(),
    lr=0.001
)

print(transfer_model.classifier)
print("Transfer-learning model is ready!")

NUM_EPOCHS = 2

train_losses = []
train_accuracies = []

for epoch in range(NUM_EPOCHS):
    transfer_model.train()

    # Keep frozen feature extractor in evaluation mode
    transfer_model.features.eval()

    running_loss = 0.0
    correct = 0
    total = 0

    for images, labels in train_loader:
        images = images.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        outputs = transfer_model(images)
        loss = criterion(outputs, labels)

        loss.backward()
        optimizer.step()

        running_loss += loss.item() * images.size(0)

        predictions = outputs.argmax(dim=1)
        correct += (predictions == labels).sum().item()
        total += labels.size(0)

    epoch_loss = running_loss / total
    epoch_accuracy = 100 * correct / total

    train_losses.append(epoch_loss)
    train_accuracies.append(epoch_accuracy)

    print(
        f"Epoch [{epoch + 1}/{NUM_EPOCHS}] "
        f"Loss: {epoch_loss:.4f} "
        f"Accuracy: {epoch_accuracy:.2f}%"
    )

print("Training complete!")

