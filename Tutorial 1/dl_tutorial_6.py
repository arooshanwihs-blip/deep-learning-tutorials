def measure_inference_time(model, input_tensor, repeats=20):
    # Warm-up
    with torch.no_grad():
        for _ in range(3):
            model(input_tensor)

    if device.type == "cuda":
        torch.cuda.synchronize()

    start = time.perf_counter()

    with torch.no_grad():
        for _ in range(repeats):
            model(input_tensor)

    if device.type == "cuda":
        torch.cuda.synchronize()

    elapsed = time.perf_counter() - start
    return (elapsed / repeats) * 1000


