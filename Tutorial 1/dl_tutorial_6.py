def predict_top5(model, input_tensor, weights, model_name):
    with torch.no_grad():
        outputs = model(input_tensor)
        probabilities = torch.nn.functional.softmax(outputs, dim=1)

        top5_probabilities, top5_indices = torch.topk(
            probabilities, k=5, dim=1
        )

    categories = weights.meta["categories"]

    print(f"\nTop 5 predictions from {model_name}:")
    print("-" * 45)

    for rank, (index, probability) in enumerate(
        zip(
            top5_indices[0].cpu().tolist(),
            top5_probabilities[0].cpu().tolist()
        ),
        start=1
    ):
        label = categories[index]
        print(f"{rank}. {label}: {probability * 100:.2f}%")

