class CustomDetectionDataset(Dataset):
    def __init__(self, image_paths, class_names, augment=False):
        """
        Args:
            image_paths (list of Path): List of image file paths for this split.
            class_names (list of str): List of class names (e.g., ['cat', 'dog']).
            augment (bool): Whether to apply horizontal flip augmentation.
        """
        self.images = sorted(image_paths)
        self.class_names = class_names
        self.class_to_id = {
            name: i + 1 for i, name in enumerate(class_names)
        }
        self.augment = augment

        if not self.images:
            raise ValueError("No images provided to the dataset class.")

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        image_path = self.images[idx]
        # The XML file is in the same directory as the image
        xml_path = image_path.with_suffix(".xml")

        image = Image.open(image_path).convert("RGB")
        root = ET.parse(xml_path).getroot()

        boxes, labels = [], []

        for obj in root.findall("object"):
            name = obj.findtext("name", default="").strip()

            if name not in self.class_to_id:
                continue

            box = obj.find("bndbox")
            xmin = float(box.findtext("xmin"))
            ymin = float(box.findtext("ymin"))
            xmax = float(box.findtext("xmax"))
            ymax = float(box.findtext("ymax"))

            # Clamp coordinates to image boundaries
            xmin = max(0, min(xmin, image.width))
            xmax = max(0, min(xmax, image.width))
            ymin = max(0, min(ymin, image.height))
            ymax = max(0, min(ymax, image.height))

            if xmax > xmin and ymax > ymin:
                boxes.append([xmin, ymin, xmax, ymax])
                labels.append(self.class_to_id[name])

        image = TF.to_tensor(image)

        target = {
            "boxes": torch.tensor(boxes, dtype=torch.float32).reshape(-1, 4),
            "labels": torch.tensor(labels, dtype=torch.int64),
            "image_id": torch.tensor([idx]),
        }

        if self.augment and random.random() < 0.5:
            image = TF.hflip(image)
            width = image.shape[-1]
            old_boxes = target["boxes"].clone()

            target["boxes"][:, 0] = width - old_boxes[:, 2]
            target["boxes"][:, 2] = width - old_boxes[:, 0]

        return image, target


def collate_fn(batch):
    return tuple(zip(*batch))

